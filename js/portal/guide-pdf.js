/* ============================ دليل الطلب (PDF) ============================
   الدليل المطبوع للموظفين: كيف يُطلب من الموقع، وكيف يُتابَع الطلب حتى
   «تم التجهيز» — بلقطاته وخطواته المرقّمة. ملفٌّ واحد public/guide-ar.pdf
   يُبنى بـ «npm run guide» (build/guide.mjs) من docs/guide/guide-ar.html.

   ويُنشر مع الموقع بجانب index.html (SITE_FILES في server/portal.js)، فرابطه
   نسبيّ: يصل إليه الموقع على GitHub Pages، والبرنامج على الحاسوب الرئيسي
   (‎/guide-ar.pdf‎ — زرّ «دليل الطلب» في «الإعدادات ← موقع الموظفين»).

   ورابطه في موضعين: رئيسية الطالب تحت «اطلب مواد»، ونافذة «الحساب» لكل
   الحسابات. ويُفتح في صفحةٍ جديدة — فيبقى الموقع كما تُرك، وفيه السلة.
   ========================================================================== */

import { h, icon } from '../ui.js';

/** مسار الدليل من صفحة الموقع. */
export const GUIDE_PDF = 'guide-ar.pdf';

/**
 * رابط «دليل الطلب (PDF)» زرّاً بعرض مكانه.
 *   onclick  يُنادى حين يُضغط — إغلاق نافذة «الحساب» مثلاً.
 *   style    تنسيقٌ إضافيّ في مكانه (المسافة فوقه).
 */
export function guideLink({ onclick = null, style = null } = {}) {
  return h('a', {
    class: 'btn btn-block p-guide-pdf', href: GUIDE_PDF, target: '_blank', rel: 'noopener', style, onclick,
  }, icon('file', 17), 'دليل الطلب (PDF)');
}
